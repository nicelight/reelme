import { test, expect } from './browser-fixture';
import { mkdir } from 'node:fs/promises';

test.use({ capturePort: 0, reducedMotion: 'reduce' });
test('admin workspace: responsive editor, themes and shared sections', async ({ page, app }) => {
  const output = process.env.REELME_BROWSER_ARTIFACTS ?? '.tasks/admin-design';
  await mkdir(output, { recursive: true });
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(app.origin + '/admin');
  await page.getByLabel('Логин').fill('admin');
  await page.getByLabel('Пароль', { exact: true }).fill(app.password);
  await page.getByRole('button', { name: 'Войти', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Новый сюжет', exact: true })).toBeVisible();
  await expect(page.locator('.admin-shell')).toHaveCSS('font-family', 'Manrope, sans-serif');
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: `${output}/empty-editor-desktop.png` });
  await page.getByRole('button', { name: 'Параметры', exact: true }).click();
  await expect(page.locator('.guide-card')).toHaveCount(5);
  await page.screenshot({ path: `${output}/guides-desktop.png`, fullPage: true });
  await expect(page.getByRole('heading', { name: 'Параметры', exact: true })).toBeVisible();
  await expect(page.getByRole('group', { name: 'Режим фотосесси', exact: true })).toBeVisible();
  await expect(page.getByLabel('Длительность отображения каждой страницы')).toBeEnabled();
  const logging = page.getByRole('switch', { name: 'Отправлять на сервер логи захвата кадра' });
  await expect(logging).not.toBeChecked();
  const photoSize = page.getByLabel('Ужимать фото перед отправкой на сервер');
  await expect(photoSize).toHaveValue('0');
  await photoSize.selectOption('2048');
  await logging.check();
  await page.getByRole('switch', { name: 'Автоматический запуск фотосессии' }).check();
  await page.getByLabel('Отсчёт перед кадром, сек.').fill('2');
  await page.getByLabel('Показ готовой серии, сек.').fill('1');
  await page.getByLabel('Показ номера посетителя, сек.').fill('4');
  await page.getByRole('button', { name: 'Сохранить параметры съёмки' }).click();
  await expect(page.getByText('Параметры сохранены для новых фотосессий.')).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: 'Параметры', exact: true }).click();
  await expect(page.getByRole('switch', { name: 'Автоматический запуск фотосессии' })).toBeChecked();
  await expect(logging).toBeChecked();
  await expect(photoSize).toHaveValue('2048');
  await expect(page.getByLabel('Показ номера посетителя, сек.')).toHaveValue('4');
  await page.screenshot({ path: `${output}/settings-desktop.png` });
  await page.getByRole('link', { name: 'Сегодня / Архив', exact: true }).click();
  await page.getByRole('button', { name: 'Архив', exact: true }).click();
  await expect(page.getByText('Пока нет прошедших мероприятий.')).toBeVisible();
  await page.screenshot({ path: `${output}/archive-desktop.png` });
  await page.goto(app.origin + '/admin');
  await expect(page.getByRole('heading', { name: 'Новый сюжет', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Светлая тема' }).click();
  await page.screenshot({ path: `${output}/editor-light.png`, fullPage: true });
  await page.getByRole('button', { name: 'Тёмная тема' }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: `${output}/empty-editor-mobile.png`, fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Параметры', exact: true }).click();
  await page.screenshot({ path: `${output}/guides-mobile.png`, fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
