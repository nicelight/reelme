/** Independent bounded editor smoke. Isolated fixture only; no paid generation.
 * Source: docs/slot-setup/matrix.md. */
import { test, expect } from '../../../tests/browser-fixture';
import { writeFile } from 'node:fs/promises';
const out = '.tasks/TASK-017-T2-FT-001-W14/ui-smoke';
test.use({ capturePort: 0 });
test('independent wide/narrow editor smoke', async ({ page, app }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  page.on('dialog', d => d.accept());
  const upload = async (label: string, file: string) => {
    await page.getByLabel(label, { exact: true }).setInputFiles(file);
    await expect(page.getByLabel('Заменить: ' + label, { exact: true })).toBeVisible();
    await expect(page.getByText('Загружаем и проверяем файл…')).toHaveCount(0);
  };
  const lock = async () => {
    await page.getByRole('button', { name: 'Зафиксировать выбор', exact: true }).click();
    await expect(page.getByText('Загружаем готовый промпт…', { exact: true })).toBeHidden();
    await expect(page.locator('#prompt')).toBeVisible();
  };
  const unlock = async () => page.getByRole('button', { name: 'Изменить выбор', exact: true }).click();
  await page.goto(app.origin + '/admin');
  await page.getByLabel('Логин').fill('admin'); await page.getByLabel('Пароль', { exact: true }).fill(app.password);
  await page.getByRole('button', { name: 'Войти', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Сюжеты', exact: false })).toBeVisible();
  await expect(page.locator('#participants')).toHaveCount(0);
  await expect(page.locator('#prompt')).toHaveCount(0);
  await upload('Изображение сюжета', app.image); await page.getByLabel('Описание', { exact: true }).fill('Независимая проверка редактора');
  await page.getByLabel('Режим', { exact: true }).selectOption('P2V');
  await page.getByLabel('Модель', { exact: true }).selectOption('fal-ai/vidu/q4/reference-to-video');
  await page.getByLabel('Участники', { exact: true }).selectOption('2');
  await page.locator('#photos-per-person').selectOption('3');
  await page.getByLabel('Разрешение', { exact: true }).selectOption('1080p');
  await page.getByLabel('Длительность, с', { exact: true }).fill('6'); await page.locator('#duration').blur();
  await page.getByLabel('Модель', { exact: true }).selectOption('google/gemini-omni-flash/v1.2/reference-to-video');
  await expect(page.locator('#participants')).toHaveValue('2'); await expect(page.locator('#photos-per-person')).toHaveValue('3');
  await expect(page.locator('#resolution')).toHaveValue('1080p'); await expect(page.locator('#duration')).toHaveValue('6');
  await expect(page.getByLabel('Распределение фотографий')).toContainText('Фото камеры: 6. Elements: 0. Дополнительные фото: 4');
  await lock(); await expect(page.locator('#model')).toBeDisabled();
  await page.locator('#prompt').fill('My authored visual direction');
  await upload('Референс 1', app.image);
  await page.getByLabel('Заменить: Референс 1', { exact: true }).setInputFiles(app.jpeg);
  await expect(page.getByText('Загружаем и проверяем файл…')).toHaveCount(0);
  await expect(page.locator('#prompt')).toHaveValue('My authored visual direction');
  await expect(page.getByText('Референсы изменены.', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: 'Открыть тесты', exact: true }).click();
  await expect(page.locator('.test-photos input[type=file]')).toHaveCount(6);
  await page.screenshot({ path: out + '/wide-configured.png', fullPage: true });
  await page.setViewportSize({ width: 375, height: 812 });
  await page.locator('#prompt').scrollIntoViewIfNeeded();
  await page.screenshot({ path: out + '/narrow-prompt.png' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Свернуть тесты', exact: true }).click();
  await unlock();
  await expect(page.getByLabel('Описание', { exact: true })).toHaveValue('Независимая проверка редактора');
  await expect(page.locator('#prompt')).toHaveCount(0);
  await page.getByLabel('Режим', { exact: true }).selectOption('V2V');
  await page.getByLabel('Модель', { exact: true }).selectOption('minimax/h3-max/recast');
  await expect(page.locator('#participants')).toHaveValue('2');
  await expect(page.locator('#photos-per-person')).toHaveValue('');
  await expect(page.getByRole('button', { name: 'Зафиксировать выбор', exact: true })).toBeDisabled();
  await page.locator('#photos-per-person').selectOption('1');
  await page.getByLabel('Разрешение', { exact: true }).selectOption('768P');
  await lock(); await expect(page.locator('#prompt')).toHaveValue(''); await expect(page.locator('#prompt')).toBeEditable();
  await expect(page.getByText('РЕКОМЕНДУЕТСЯ ОСТАВИТЬ ПРОМПТ ПУСТЫМ!', { exact: true })).toBeVisible();
  await upload('Исходное видео', app.video);
  const source = await page.locator('.materials video').getAttribute('src');
  await unlock(); await lock();
  await expect(page.locator('.materials video')).toHaveAttribute('src', source!);
  await page.locator('#prompt').fill('Optional Recast instruction');
  await expect(page.locator('#prompt')).toHaveValue('Optional Recast instruction');
  await page.locator('.materials').scrollIntoViewIfNeeded();
  await page.screenshot({ path: out + '/narrow-recast.png' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator('#prompt').blur();
  await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))));
  await page.screenshot({ path: out + '/wide-recast.png', fullPage: true });
  expect(errors).toEqual([]);
  await writeFile(out + '/observations.json', JSON.stringify({ compatibleUpperValuesPreserved: true, incompatibleRecastFramesCleared: true, manualPromptPreservedOnSameCountReplacement: true, recastEmptyEditable: true, boundVideoRetainedOnUnlock: true, wide: [1440,1000], narrow: [375,812], horizontalOverflow: false, pageErrors: errors, cameraOrPaidProviderInvocations: false }, null, 2));
});
