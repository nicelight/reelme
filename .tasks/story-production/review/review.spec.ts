import { test, expect } from '../../../tests/browser-fixture';
import { request as apiRequest } from '@playwright/test';
import { readFile, writeFile } from 'node:fs/promises';
import sharp from 'sharp';
import { randomUUID } from 'node:crypto';
const out = '.tasks/story-production/review';
test.use({ capturePort: 5543 });
test('independent production visual and interaction review', async ({ page, app }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  const admin = await apiRequest.newContext({ baseURL: app.origin, extraHTTPHeaders: { Origin: app.origin } });
  expect((await admin.post('/api/auth/login', { data: { username: 'admin', password: app.password } })).status()).toBe(200);
  const upload = async (buffer: Buffer, name: string, mimeType: string) => {
    const result = await admin.post('/api/admin/slot-media', { multipart: { file: { name, mimeType, buffer } } });
    expect(result.status()).toBe(201); return (await result.json()).id;
  };
  const sprite = 'src/client/capture/story-prototype/assets/portraits.png';
  const meta = await sharp(sprite).metadata();
  const w = Math.floor(meta.width! / 3), h = Math.floor(meta.height! / 3);
  const positions = [[1, 0], [2, 0], [0, 1], [0, 2], [1, 1]];
  const names = ['Космическая миссия', 'Королевский бал', 'Герой кино', 'Арт-реальность', 'Путешествие во времени'];
  const thumbnails = [];
  for (const [x, y] of positions) thumbnails.push(await upload(await sharp(sprite).extract({ left: x*w, top: y*h, width:w, height:h }).png().toBuffer(), 'story.png', 'image/png'));
  const demoId = await upload(await readFile('docs/video templates/1794213414058-yjz13u263xc.mp4'), 'demo.mp4', 'video/mp4');
  const slots: any[] = [];
  for (let i=0; i<13; i++) {
    const result = await admin.post('/api/admin/slots', { data: { id:randomUUID(), description: names[i%5] + (i<5 ? '' : ` ${i+1}`), visible:true, thumbnailId:thumbnails[i%5], referenceIds:[], mode:'P2V', model:'kling/v4/reference-to-video', participants:1, photosPerParticipant:4, orientation:'landscape', aspectRatio:'16:9', resolution:'720p', duration:5, prompt:'Visitor @Element1', ...(i===2 ? {demoId}: {}) } });
    expect(result.status(), await result.text()).toBe(201); slots.push(await result.json());
  }
  await admin.dispose();
  await page.addInitScript(key => localStorage.setItem('reelme.installationKey', key), app.installationKey);
  await page.goto(`${app.captureOrigin}/reelme.html#slot=${slots[2].id}`);
  await expect(page.locator('.story')).toHaveCount(13);
  await expect(page.locator('.story:not(.offstage)')).toHaveCount(5);
  const video = page.locator('.center video');
  await expect.poll(() => video.evaluate((v:HTMLVideoElement) => v.readyState)).toBeGreaterThanOrEqual(2);
  await video.evaluate(async(v:HTMLVideoElement)=>{v.muted=true;await v.play();v.pause();});
  if (process.env.REVIEW_RECAPTURE_ONLY) {
    await page.setViewportSize({width:1280,height:720});
    await page.waitForTimeout(850);
    expect(await page.locator('.center').evaluate(e=>Math.round(e.getBoundingClientRect().width))).toBe(512);
    await page.screenshot({path:`${out}/production-1280.png`,fullPage:true});
    await page.route(`**/api/catalog/${slots[2].id}/media/${demoId}`, route=>route.fulfill({status:503,body:'Controlled review failure'}));
    await page.reload();
    await expect(page.locator('.center').getByText('Видео не загрузилось.',{exact:true})).toBeVisible();
    await page.waitForTimeout(850);
    await page.screenshot({path:`${out}/production-video-fallback.png`,fullPage:true});
    return;
  }
  await page.waitForTimeout(800);
  await page.screenshot({ path:`${out}/production-1672.png`, fullPage:true });
  const geometry = await page.evaluate(() => { const box=(selector:string)=>{ const r=document.querySelector(selector)!.getBoundingClientRect();return {x:r.x,y:r.y,width:r.width,height:r.height}};return {intro:box('.story-intro'),center:box('.story.center'),viewport:{width:innerWidth,height:innerHeight},overflow:document.documentElement.scrollWidth>innerWidth}; });
  expect(Math.abs(geometry.intro.x+geometry.intro.width/2-836)).toBeLessThan(1);
  expect(geometry.overflow).toBe(false);
  await video.evaluate((v:HTMLVideoElement) => { (window as any).reviewVideo=v;v.muted=true;return v.play(); });
  await page.getByRole('button',{name:'Следующий сюжет',exact:true}).click();
  await page.waitForTimeout(270);
  await page.screenshot({path:`${out}/production-transition.png`,fullPage:true});
  expect(await page.evaluate(()=>(window as any).reviewVideo.paused)).toBe(true);
  await page.waitForTimeout(650);
  await page.getByRole('button',{name:'Сюжет 13: Герой кино 13',exact:true}).click();
  await expect(page.locator('.center .story-heading p')).toHaveText('Герой кино 13');
  for(let i=0;i<8;i++) await page.getByRole('button',{name:'Следующий сюжет',exact:true}).click();
  await page.waitForTimeout(1000);
  await expect(page.locator('.center')).toHaveCount(1);
  await expect(page.locator('.story:not(.offstage)')).toHaveCount(5);
  await page.getByRole('button',{name:'Сюжет 3: Герой кино',exact:true}).click();
  await page.waitForTimeout(900);
  await page.setViewportSize({width:1280,height:720});
  await page.waitForTimeout(850);
  await page.screenshot({path:`${out}/production-1280.png`,fullPage:true});
  expect(await page.locator('.center').evaluate(e=>Math.round(e.getBoundingClientRect().width))).toBe(512);
  const blocked = `**/api/catalog/${slots[2].id}/media/${demoId}`;
  await page.route(blocked, route=>route.fulfill({status:503,body:'Controlled review failure'}));
  await page.reload();
  await expect(page.locator('.center').getByText('Видео не загрузилось.',{exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Выбрать этот сюжет',exact:true})).toBeVisible();
  await page.waitForTimeout(850);
  await page.screenshot({path:`${out}/production-video-fallback.png`,fullPage:true});
  await page.unroute(blocked);
  await page.locator('.center').getByRole('button',{name:'Повторить загрузку',exact:true}).click();
  await expect.poll(() => page.locator('.center video').evaluate((v:HTMLVideoElement)=>v.readyState)).toBeGreaterThanOrEqual(2);
  expect(errors).toEqual([]);
  await writeFile(`${out}/observations.json`,JSON.stringify({geometry,checks:{all13:true,fiveVisible:true,thirteenthAccessible:true,rapidClicksSettle:true,previousVideoPaused:true,videoFallbackRetry:true,ctaAvailableDuringMediaFailure:true},pageErrors:errors},null,2));
});
